// Get permissions for a role
exports.getRolePermissions = (role) => {
  return ROLE_PERMISSIONS[role.toUpperCase()] || {};
};

// Check if user has permission
exports.hasPermission = (user, module, action) => {
  if (!user || !user.role) return false;
  
  const rolePermissions = this.getRolePermissions(user.role);
  
  if (!rolePermissions[module]) return false;
  
  return rolePermissions[module].includes(action);
};

// Check if user can access module
exports.canAccessModule = (user, module) => {
  return this.hasPermission(user, module, PERMISSIONS.VIEW);
};

// Check if user can create in module
exports.canCreate = (user, module) => {
  return this.hasPermission(user, module, PERMISSIONS.CREATE);
};

// Check if user can edit in module
exports.canEdit = (user, module) => {
  return this.hasPermission(user, module, PERMISSIONS.EDIT);
};

// Check if user can delete in module
exports.canDelete = (user, module) => {
  return this.hasPermission(user, module, PERMISSIONS.DELETE);
};

// Get all modules user can access
exports.getAccessibleModules = (user) => {
  if (!user || !user.role) return [];
  
  const rolePermissions = this.getRolePermissions(user.role);
  return Object.keys(rolePermissions).filter(module => 
    this.canAccessModule(user, module)
  );
};

